'use strict';

/**
 * Builds public/app.js from the feature files in public/src/.
 *
 * The browser still loads one script, public/app.js, exactly as before: the
 * files in public/src/ are its parts, joined in file-name order inside the
 * one function scope they have always shared. So any function can still call
 * any other, and nothing becomes a global. Order matters only for top-level
 * statements that run as the page loads (constants, event wiring, start-up);
 * the number prefixes keep those in their original order.
 *
 * Edit public/src/, then run `npm run build`. Never edit public/app.js by
 * hand: `npm test` fails when it does not match public/src/.
 *
 *   node scripts/build-app.js           write public/app.js
 *   node scripts/build-app.js --check   exit 1 if public/app.js is out of date
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'public', 'src');
const OUT = path.join(ROOT, 'public', 'app.js');

const PROLOGUE = `/* SBS Management Tool - client application.
 *
 * A switch is the unit of work: one tab per device, holding a Health page
 * (the entry point) plus SNMP, SSH and tech-support views that all reuse
 * the same host. Nothing is written to disk unless the user clicks Save.
 *
 * GENERATED by scripts/build-app.js from public/src/*.js. Edit those files
 * and run \`npm run build\`; do not edit this file.
 */
(function () {
  'use strict';`;
const EPILOGUE = '\n})();\n';

function build() {
  const files = fs.readdirSync(SRC_DIR).filter((f) => /^\d\d-[a-z0-9-]+\.js$/.test(f)).sort();
  if (!files.length) throw new Error('No source files in ' + SRC_DIR);
  const parts = files.map((f) => '\n\n' + fs.readFileSync(path.join(SRC_DIR, f), 'utf8').replace(/\s+$/, ''));
  return PROLOGUE + parts.join('') + EPILOGUE;
}

if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('public/app.js does not match public/src/. Run: npm run build');
      process.exit(1);
    }
    console.log('public/app.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('Wrote public/app.js from ' + fs.readdirSync(SRC_DIR).filter((f) => f.endsWith('.js')).length + ' files.');
  }
}

module.exports = { build };
